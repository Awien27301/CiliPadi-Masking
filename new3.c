static int equal16(const u8 a[16], const u8 b[16])
{
    return memcmp(a, b, 16) == 0;
}

static void xor16(u8 out[16], const u8 a[16], const u8 b[16])
{
    for (int i = 0; i < 16; i++)
        out[i] = (u8)((a[i] ^ b[i]) & 0xF);
}

static void recombine(u8 out[16], const u8 s0[16], const u8 s1[16])
{
    xor16(out, s0, s1);
}

/* ================================================================
 * GF(16)
 * Polynomial: x^4 + x + 1
 * ================================================================ */
static u8 gf16_mul(u8 a, u8 b)
{
    u8 p = 0;
    a &= 0xF;
    b &= 0xF;

    for (int i = 0; i < 4; i++) {
        if (b & 1)
            p ^= a;

        u8 hi = a & 0x8;
        a = (u8)((a << 1) & 0xF);

        if (hi)
            a ^= 0x3;

        b >>= 1;
    }

    return p & 0xF;
}

/* ================================================================
 * LED LINEAR LAYERS
 * ================================================================ */
static const u8 MDS[4][4] = {
    {0x4, 0x1, 0x2, 0x2},
    {0x8, 0x6, 0x5, 0x6},
    {0xB, 0xE, 0xA, 0x9},
    {0x2, 0x2, 0xF, 0xB}
};

static void shift_rows(u8 s[16])
{
    u8 t[16];

    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            t[4*r+c] = s[4*r + ((c+r) & 3)];

    memcpy(s, t, 16);
}

static void mix_columns(u8 s[16])
{
    u8 t[16] = {0};

    for (int c = 0; c < 4; c++) {
        for (int r = 0; r < 4; r++) {
            u8 v = 0;
            for (int k = 0; k < 4; k++)
                v ^= gf16_mul(MDS[r][k], s[4*k+c]);

            t[4*r+c] = v & 0xF;
        }
    }

    memcpy(s, t, 16);
}

/* ================================================================
 * PRESENT S-BOX
 * ================================================================ */
static const u8 PRESENT_SBOX[16] = {
    0xC,0x5,0x6,0xB,
    0x9,0x0,0xA,0xD,
    0x3,0xE,0xF,0x8,
    0x4,0x7,0x1,0x2
};

static void sub_cells(u8 s[16])
{
    for (int i = 0; i < 16; i++)
        s[i] = PRESENT_SBOX[s[i] & 0xF];
}

/* ================================================================
 * FIRST-ORDER ISW AND
 *
 * a = a0 XOR a1
 * b = b0 XOR b1
 *
 * z0 = (a0 & b0) XOR r
 * z1 = (a1 & b1) XOR (a0 & b1)
 *      XOR (a1 & b0) XOR r
 * ================================================================ */
static mbit isw_and(mbit a, mbit b)
{
    u8 r = rand_bit();

    mbit z;
    z.s0 = (u8)(((a.s0 & b.s0) ^ r) & 1);
    z.s1 = (u8)(((a.s1 & b.s1)
               ^ (a.s0 & b.s1)
               ^ (a.s1 & b.s0)
               ^ r) & 1);

    return z;
}

static mbit mbit_xor(mbit a, mbit b)
{
    mbit z = {
        (u8)((a.s0 ^ b.s0) & 1),
        (u8)((a.s1 ^ b.s1) & 1)
    };
    return z;
}

static mbit masked_monomial(const mbit x[4], unsigned mask)
{
    if (mask == 0) {
        mbit one = {1, 0};
        return one;
    }

    int first = -1;

    for (int i = 0; i < 4; i++) {
        if (mask & (1u << i)) {
            first = i;
            break;
        }
    }

    mbit acc = x[first];

    for (int i = first + 1; i < 4; i++) {
        if (mask & (1u << i))
            acc = isw_and(acc, x[i]);
    }

    return acc;
}

/*
 * PRESENT S-box ANF.
 */
static void masked_present_sbox(u8 in0, u8 in1, u8 *out0, u8 *out1)
{
    static const unsigned anf[4][8] = {
        {0x1,0x4,0x6,0x8,0,0,0,0},
        {0x2,0x7,0x8,0xA,0xB,0xC,0xD,0},
        {0x0,0x3,0x4,0x8,0x9,0xA,0xB,0xD},
        {0x0,0x1,0x2,0x6,0x7,0x8,0xB,0xD}
    };

    static const int terms[4] = {4,7,8,8};

    mbit x[4];

    for (int b = 0; b < 4; b++) {
        x[b].s0 = (u8)((in0 >> b) & 1);
        x[b].s1 = (u8)((in1 >> b) & 1);
    }

    u8 a0 = 0;
    u8 a1 = 0;

    for (int ob = 0; ob < 4; ob++) {
        mbit y = {0,0};

        for (int j = 0; j < terms[ob]; j++) {
            mbit m = masked_monomial(x, anf[ob][j]);
            y = mbit_xor(y, m);
        }

        a0 |= (u8)((y.s0 & 1) << ob);
        a1 |= (u8)((y.s1 & 1) << ob);
    }

    *out0 = a0 & 0xF;
    *out1 = a1 & 0xF;
}

static void masked_sub_cells(u8 s0[16], u8 s1[16])
{
    for (int i = 0; i < 16; i++) {
        u8 o0, o1;

        masked_present_sbox(s0[i], s1[i], &o0, &o1);

        s0[i] = o0;
        s1[i] = o1;
    }
}

/* ================================================================
 * MASKING
 * ================================================================ */
static void mask_state(const u8 secret[16], u8 s0[16], u8 s1[16])
{
    for (int i = 0; i < 16; i++) {
        s0[i] = rand_nibble();
        s1[i] = (u8)((secret[i] ^ s0[i]) & 0xF);
    }
}

/*
 * Public round constant is applied to share 0 only:
 *
 * (Share0 XOR RC) XOR Share1
 * = Secret XOR RC
 */
static void masked_add_constant(u8 s0[16], const u8 rc[16])
{
    for (int i = 0; i < 16; i++)
        s0[i] ^= rc[i];
}

/* ================================================================
 * UNMASKED LED ROUND
 * ================================================================ */
static void led_round_unmasked(u8 s[16], const u8 rc[16])
{
    xor16(s, s, rc);
    sub_cells(s);
    shift_rows(s);
    mix_columns(s);
}

/* ================================================================
 * CLEAN MASKED LED ROUND OUTPUT
 * ================================================================ */
static void led_round_masked(u8 s0[16], u8 s1[16],
                             const u8 rc[16],
                             const char *round_name,
                             const char *input_name)
{
    u8 rec[16];

    printf("\n  +--------------------------------------------------------------+\n");
    printf("  | %-60s |\n", round_name);
    printf("  +--------------------------------------------------------------+\n");

    char input_label[128];
    snprintf(input_label, sizeof(input_label), "INPUT SHARES : %s", input_name);

    print_matrix_pair(input_label, s0, s1);
    recombine(rec, s0, s1);

    char recomb_label[128];
    snprintf(recomb_label, sizeof(recomb_label), "Recombined input (%s)", input_name);
    print_hex64(recomb_label, rec);

    masked_add_constant(s0, rc);

    print_matrix_pair("AFTER AddConstant", s0, s1);
    recombine(rec, s0, s1);
    print_hex64("Recombined after AC", rec);

    masked_sub_cells(s0, s1);

    print_matrix_pair("AFTER SubCells (ISW)", s0, s1);
    recombine(rec, s0, s1);
    print_hex64("Recombined after SC", rec);

    shift_rows(s0);
    shift_rows(s1);

    print_matrix_pair("AFTER ShiftRows", s0, s1);
    recombine(rec, s0, s1);
    print_hex64("Recombined after SR", rec);

    mix_columns(s0);
    mix_columns(s1);

    print_matrix_pair("AFTER MixColumns", s0, s1);
    recombine(rec, s0, s1);
    print_hex64("Recombined after MCS", rec);
}


