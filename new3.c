/*
 * ================================================================
 * CiliPadi-Mild - Masked F1/F2 Demonstration (Permutation Round 2)
 * First-Order Boolean Masking + ISW
 * ================================================================
 *
 * REAL CILIPADI-MILD DATA:
 *   Round 2 input and expected F1/F2 outputs are taken directly
 *   from the supplied CiliPadi-Mild execution trace.
 *
 * Scope:
 *   - NO CiliPadi branch update
 *   - Only demonstrate masked F1(X1) and F2(X3)
 *   - Verify recombined masked output == unmasked output
 *
 * Flow:
 *   Secret -> Random Mask -> Share0/Share1
 *          -> AddConstant
 *          -> PRESENT S-box using ISW AND
 *          -> ShiftRows
 *          -> MixColumns
 *          -> LED Round 2
 *          -> Recombine
 *          -> Compare with unmasked F output
 *
 * Compile:
 *   gcc -std=c11 -Wall -Wextra CiliPadi_Mild_Round2_ISW_CLEAN.c \
 *       -o CiliPadi_Mild_Round2_ISW_CLEAN
 *
 * Run:
 *   ./CiliPadi_Mild_Round2_ISW_CLEAN
 *
 * Save output:
 *   ./CiliPadi_Mild_Round2_ISW_CLEAN > CiliPadi_Mild_Round2_ISW_CLEAN.txt
 * ================================================================
 */

#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <stdlib.h>
#include <time.h>

typedef uint8_t u8;

typedef struct {
    u8 s0;
    u8 s1;
} mbit;

/* ================================================================
 * FRESH RANDOMNESS
 *
 * New randomness is generated every time the program runs.
 *
 * Primary source:
 *   /dev/urandom
 *
 * Used for:
 *   - Share 0 random masks
 *   - Share 1 derivation
 *   - Fresh random bit r in every ISW AND
 *
 * The CiliPadi-Mild data itself is NOT random.
 * X1, X3, round constants, and expected F outputs come directly
 * from the supplied cilipadi-mild-steps(5).txt trace.
 * ================================================================ */

static uint32_t fallback_state = 0;

static uint32_t fallback_rng32(void)
{
    if (fallback_state == 0) {
        fallback_state = (uint32_t)time(NULL)
                       ^ (uint32_t)(uintptr_t)&fallback_state;
    }

    uint32_t x = fallback_state;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    fallback_state = x;
    return x;
}

static u8 secure_random_byte(void)
{
    FILE *fp = fopen("/dev/urandom", "rb");

    if (fp != NULL) {
        u8 b;
        size_t n = fread(&b, 1, 1, fp);
        fclose(fp);

        if (n == 1)
            return b;
    }

    return (u8)(fallback_rng32() & 0xFF);
}

static u8 rand_nibble(void)
{
    return (u8)(secure_random_byte() & 0x0F);
}

static u8 rand_bit(void)
{
    return (u8)(secure_random_byte() & 0x01);
}

