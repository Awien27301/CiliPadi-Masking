static void xor_share_pair(u8 out0[16], u8 out1[16],
                           const u8 a0[16], const u8 a1[16],
                           const u8 b0[16], const u8 b1[16])
{
    for (int i = 0; i < 16; i++) {
        out0[i] = (u8)((a0[i] ^ b0[i]) & 0xF);
        out1[i] = (u8)((a1[i] ^ b1[i]) & 0xF);
    }
}

